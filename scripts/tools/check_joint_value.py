def extract_and_save_angles(data):
    angle_data = ""
    pattern = r'positions:\s*(\[.*?\])'
    matches = re.findall(pattern, data)
    # print(matches)

    for match in matches:
        match_with_comma = match.replace(']', ']')
        math_with_comma_without_kakko = match_with_comma.replace('[', '').replace(']', '')
        # 6つの関節角度までで改行
        angle_data += math_with_comma_without_kakko + '\n'

    return angle_data

# 関節限界チェック関数
def check_joint_limits(path_data):
    # 改行ごとにデータを分割してリストに変換
    path_points = path_data.strip().split('\n')
    results = []
    
    for i, point in enumerate(path_points, start=1):
        # 各行をリストに変換し、空の要素を除外
        joint_angles = [float(angle) for angle in point.split(',') if angle.strip()]
        
        # 各行が6要素でなければスキップ（もしくはエラー処理）
        if len(joint_angles) != 6:
            print(f"Warning: Point {i} does not have exactly 6 joint angles. Skipping.")
            continue
        
        point_result = {}
        for j, angle in enumerate(joint_angles):
            joint_name = f'joint{j+1}'
            limit_min, limit_max = joint_limits[joint_name]
            
            # 関節角度が限界範囲内にあるかを確認
            if limit_min <= angle <= limit_max:
                point_result[joint_name] = "Within limits"
            else:
                point_result[joint_name] = f"Out of limits (Angle: {angle}, Limits: {limit_min}, {limit_max})"
        
        results.append({f"Point {i}": point_result})
    
    return results

